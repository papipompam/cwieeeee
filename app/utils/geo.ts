const provinceToRegionMap = new Map<string, Region>()
for (const [region, provinces] of Object.entries(REGION_PROVINCES)) {
  for (const province of provinces) {
    provinceToRegionMap.set(province, region as Region)
  }
}

export const PROVINCES = Array.from(provinceToRegionMap.keys()).sort((a, b) => a.localeCompare(b, 'th'))

export const getRegionByProvince = (province: string): string => {
  if (!province) return '-'
  return provinceToRegionMap.get(province.trim()) ?? '-'
}
